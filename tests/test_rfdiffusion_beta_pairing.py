def test_parse_target_strand_ranges_and_register_counts():
    assert inputs.parse_residue_selection("B99-103, B110-114", "B") == [
        99, 100, 101, 102, 103, 110, 111, 112, 113, 114
    ]
    assert inputs.estimate_register_count(65, 6, 1) == 60
    # Both ordered assignments of two binder strands to the two target strands
    # are generated by the published recursive tensor script.
    assert inputs.estimate_register_count(65, 6, 2) == 2652


@pytest.mark.parametrize("selection", ["A99-103", "B0-3", "B103-99", "B99-100"])
def test_invalid_target_strand_ranges_are_rejected(selection):
    with pytest.raises(ValueError):
        numbers = inputs.parse_residue_selection(selection, "B")
        groups = inputs._selection_groups(numbers)
        if any(len(group) < 3 for group in groups):
            raise ValueError("Each selected segment must include at least three residues.")


def test_paper_example_is_validated_and_normalized(tmp_path):
    request = inputs.prepare_request(
        {
            "target_pdb": str(PAPER_EXAMPLE),
            "target_chain": "B",
            "target_beta_strands": "B99-103",
        }
    )
    assert request["register_count"] == 60
    assert request["model_weights"] == "Complex_Fold_base"

    normalized = tmp_path / "target.pdb"
    groups, normalized_to_original = _normalize_target(
        PAPER_EXAMPLE, "B", list(range(99, 104)), normalized
    )
    assert groups == [[34, 35, 36, 37, 38]]
    assert normalized_to_original[34] == "B99"
    target_residues = {
        int(line[22:26])
        for line in normalized.read_text().splitlines()
        if line.startswith("ATOM  ") and line[12:16].strip() == "CA"
    }
    assert target_residues == set(range(1, 74))


def test_inference_command_matches_installed_scaffolded_sampler_config(tmp_path):
    run_dir = tmp_path / "run"
    target = run_dir / "artifacts/raw/rfdiffusion_beta_pairing/input/target.pdb"
    tensor_dir = run_dir / "artifacts/raw/rfdiffusion_beta_pairing/interface_tensors"
    params = {
        "gpu_device": "0",
        "binder_length": 65,
        "target_residue_map": {i: f"B{i}" for i in range(1, 74)},
        "target_beta_residue_ids": ["A34", "A35", "A36"],
        "seed": 7,
        "num_designs": 1,
        "model_weights": "Complex_base",
        "timesteps": 5,
        "systematic_sampling": True,
    }
    command = _docker_rfdiffusion_command(run_dir, target, tensor_dir, params)
    assert "inference.model_runner=ScaffoldedSampler" in command
    assert "scaffoldguided.scaffoldguided_enable=True" in command
    assert "scaffoldguided.scaffoldguided=True" not in command
    assert not any(value.startswith("inference.ckpt_override_path=") for value in command)


def test_beta_pairing_pipeline_templates_validate():
    graph = new_graph("rfdiffusion_beta_pairing")
    checked = validate_graph(graph)
    assert checked["order"]
    kinds = [node["data"]["kind"] for node in graph["nodes"]]
    assert kinds == ["rfdiffusion_beta_pairing", "ligandmpnn", "af2", "results"]
    af2 = next(node for node in graph["nodes"] if node["data"]["kind"] == "af2")
    assert af2["data"]["label"] == "AlphaFold2 Initial Guess"
    assert af2["data"]["params"]["use_binder_template"] is False

    continuation = new_graph("rfdiffusion_beta_pairing_generated")
    validate_graph(continuation)
    assert continuation["nodes"][0]["data"]["kind"] == "backbone_source"
